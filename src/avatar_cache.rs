use std::io::Cursor;
use std::path::Path;
use std::time::Duration;

use color_eyre::eyre::Result;
use image::{DynamicImage, ImageEncoder, ImageFormat, ImageReader, Limits};
use rusqlite::{Connection, OpenFlags, params};

const AVATAR_EDGE: u32 = 64;
const MAX_SOURCE_EDGE: u32 = 512;
const MAX_DOWNLOAD_BYTES: usize = 256 * 1024;
const MAX_PNG_BYTES: u16 = 24 * 1024;
const DOWNLOAD_TIMEOUT: Duration = Duration::from_secs(10);
const MAX_CACHE_BYTES: u32 = 16 * 1024 * 1024;
const MAX_CACHE_ENTRIES: u32 = 512;

pub struct AvatarCache(Connection);

impl AvatarCache {
    pub fn open_default() -> Option<Self> {
        let dir = dirs::cache_dir()?.join("io.blacktop.disctui");
        Self::open(&dir)
            .inspect_err(|err| tracing::debug!("avatar cache unavailable: {err}"))
            .ok()
    }

    pub(crate) fn open(dir: &Path) -> Result<Self> {
        std::fs::create_dir_all(dir)?;
        // macOS standard cache paths can have symlinked ancestors such as /var.
        let path = dir.canonicalize()?.join("avatars.sqlite3");
        let conn = Connection::open_with_flags(
            path,
            OpenFlags::default() | OpenFlags::SQLITE_OPEN_NOFOLLOW,
        )?;
        // Cache contention should remain a miss while the TUI updates.
        conn.busy_timeout(Duration::ZERO)?;
        let page_size: u32 = conn.pragma_query_value(None, "page_size", |row| row.get(0))?;
        conn.pragma_update(None, "max_page_count", MAX_CACHE_BYTES / page_size.max(1))?;
        conn.execute_batch(
            "CREATE TABLE IF NOT EXISTS avatars (key TEXT NOT NULL UNIQUE, png BLOB NOT NULL)",
        )?;
        Ok(Self(conn))
    }

    pub fn get(&self, key: &str) -> Option<DynamicImage> {
        let png: Vec<u8> = self
            .0
            .prepare_cached("SELECT png FROM avatars WHERE key = ?1 AND length(png) <= ?2")
            .ok()?
            .query_row(params![key, MAX_PNG_BYTES], |row| row.get(0))
            .ok()?;
        decode_cached(&png)
    }

    pub fn put(&mut self, key: &str, png: &[u8]) -> rusqlite::Result<()> {
        let transaction = self.0.transaction()?;
        transaction.execute(
            "INSERT OR REPLACE INTO avatars (key, png) VALUES (?1, ?2)",
            params![key, png],
        )?;
        transaction.execute(
            "DELETE FROM avatars WHERE rowid IN (
                SELECT rowid FROM avatars ORDER BY rowid DESC LIMIT -1 OFFSET ?1
            )",
            [MAX_CACHE_ENTRIES],
        )?;
        transaction.commit()
    }
}

/// Only cache public, content-versioned user and server icons generated by the transport.
pub fn key(url: &str) -> Option<&str> {
    let key = url
        .strip_prefix("https://cdn.discordapp.com/")?
        .strip_suffix(".png?size=64")?;
    let (kind, asset) = key.split_once('/')?;
    let (id, hash) = asset.split_once('/')?;
    (matches!(kind, "avatars" | "icons")
        && (1..=20).contains(&id.len())
        && id.bytes().all(|byte| byte.is_ascii_digit())
        && (1..=64).contains(&hash.len())
        && hash
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'))
    .then_some(key)
}

pub fn decode_cached(png: &[u8]) -> Option<DynamicImage> {
    if png.len() > usize::from(MAX_PNG_BYTES) {
        return None;
    }
    decode_png(png, AVATAR_EDGE)
}

fn decode_png(bytes: &[u8], max_edge: u32) -> Option<DynamicImage> {
    let mut limits = Limits::default();
    limits.max_image_width = Some(max_edge);
    limits.max_image_height = Some(max_edge);
    limits.max_alloc = Some(8 * 1024 * 1024);
    let mut reader = ImageReader::with_format(Cursor::new(bytes), ImageFormat::Png);
    reader.limits(limits);
    reader.decode().ok()
}

pub(crate) fn normalize(bytes: &[u8]) -> Option<Vec<u8>> {
    let image = decode_png(bytes, MAX_SOURCE_EDGE)?;
    let rgba = if image.width() > AVATAR_EDGE || image.height() > AVATAR_EDGE {
        image.thumbnail(AVATAR_EDGE, AVATAR_EDGE).into_rgba8()
    } else {
        image.into_rgba8()
    };
    let mut png = Vec::new();
    image::codecs::png::PngEncoder::new(&mut png)
        .write_image(
            &rgba,
            rgba.width(),
            rgba.height(),
            image::ExtendedColorType::Rgba8,
        )
        .ok()?;
    (png.len() <= usize::from(MAX_PNG_BYTES)).then_some(png)
}

pub async fn fetch_png(url: &str) -> Option<Vec<u8>> {
    let client = reqwest::Client::builder()
        .redirect(reqwest::redirect::Policy::none())
        .timeout(DOWNLOAD_TIMEOUT)
        .build()
        .ok()?;
    let mut response = client.get(url).send().await.ok()?;
    if !response.status().is_success()
        || response
            .content_length()
            .is_some_and(|size| size > MAX_DOWNLOAD_BYTES as u64)
    {
        return None;
    }
    let mut bytes = Vec::new();
    while let Some(chunk) = response.chunk().await.ok()? {
        if chunk.len() > MAX_DOWNLOAD_BYTES.saturating_sub(bytes.len()) {
            return None;
        }
        bytes.extend_from_slice(&chunk);
    }
    match tokio::task::spawn_blocking(move || normalize(&bytes)).await {
        Ok(result) => result,
        Err(err) => {
            tracing::debug!("avatar decoder stopped: {err}");
            None
        }
    }
}

#[cfg(test)]
#[expect(clippy::unwrap_used, reason = "test fixture encoding must succeed")]
mod tests {
    use crate::avatar_cache::{decode_cached, key, normalize};
    use image::{DynamicImage, ImageFormat};
    use std::io::Cursor;

    #[test]
    fn avatar_normalization_preserves_aspect_ratio_and_rejects_large_sources() {
        let encode = |width, height| {
            let mut source = Cursor::new(Vec::new());
            DynamicImage::new_rgba8(width, height)
                .write_to(&mut source, ImageFormat::Png)
                .unwrap();
            source.into_inner()
        };
        let png = normalize(&encode(128, 96)).unwrap();
        let image = decode_cached(&png).unwrap();
        assert_eq!((image.width(), image.height()), (64, 48));
        assert!(normalize(&encode(513, 1)).is_none());
    }

    #[test]
    fn cache_keys_exclude_attachments_and_signed_or_malformed_urls() {
        assert_eq!(
            key("https://cdn.discordapp.com/icons/123/a_abcd.png?size=64"),
            Some("icons/123/a_abcd")
        );
        for url in [
            "https://cdn.discordapp.com/attachments/123/abcd.png?size=64",
            "https://cdn.discordapp.com/avatars/123/abcd.png?signature=secret&size=64",
            "https://cdn.discordapp.com/avatars/123/../abcd.png?size=64",
            "https://other.example/avatars/123/abcd.png?size=64",
        ] {
            assert!(key(url).is_none(), "{url}");
        }
    }
}
